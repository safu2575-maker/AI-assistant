const assert = require('node:assert/strict');
const {chartTimeline} = require('../.tmp/test/qna/chartTimeline');
const {filterChartPeriods} = require('../.tmp/test/qna/chartWindow');
const base={type:'line',title:'Rent by Tenant and Year',groupNames:['Tenant','Year'],groupValues:[['B','2025'],['A','2024'],['A','2025']],labels:['B · 2025','A · 2024','A · 2025'],values:[20,0,30],valueLabels:['20','0','30'],rowIndices:[[0],[1],[2]]};
const snapshot=JSON.stringify(base), result=chartTimeline(base);
assert.deepEqual(result.periods.map(p=>p.label),['2024','2025']);
assert.equal(result.series.find(s=>s.name==='A').points.get(2024*12).value,0);
assert.equal(result.series.find(s=>s.name==='A').points.get(2025*12).source,2);
assert.equal(result.series.find(s=>s.name==='B').points.has(2024*12),false,'missing observations are not zeroes');
assert.equal(JSON.stringify(base),snapshot,'source chart remains unchanged');
const window=filterChartPeriods(base,result,2025*12,2025*12);
assert.deepEqual(window.labels,['B · 2025','A · 2025'],'period filtering preserves original category layout and order');
assert.deepEqual(window.values,[20,30]);
assert.deepEqual(window.rowIndices,[[0],[2]],'point identities survive period filtering');
assert.equal(chartTimeline({...base,groupValues:[['A','2024'],['A','2024'],['A','2025']]}),undefined,'ambiguous duplicate cells are not summed');
const monthly=chartTimeline({...base,groupNames:['Year','Month'],groupValues:[['2025','January'],['2024','December'],['2025','March']]});
assert.deepEqual(monthly.periods.map(p=>p.label),['Dec 2024','Jan 2025','Mar 2025']);
assert.equal(monthly.monthly,true);
assert.equal(chartTimeline({...base,groupNames:['Tenant'],groupValues:[['2025'],['2024'],['2026']]}),undefined,'numeric categories are not interpreted as years');
const multi=chartTimeline({...base,series:[{name:'Rent',values:base.values,valueLabels:base.valueLabels},{name:'Sales',values:[2,3,4],valueLabels:['2','3','4']}]});
assert.equal(multi.series.length,4,'category and measure combinations are separate series');
console.log('Chart timeline chronology, missing data, selection mapping and grain checks passed.');
