import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {model,fixture} from './visual-fixture.mjs';
const {ModelSession}=createRequire(import.meta.url)('../dist/visual-server.cjs');
const f=fixture(),session=new ModelSession(model,'fixture-token',f.fetcher);
const kpi={id:'ratio',name:'Rent ratio',formula:'DIVIDE([Rent Measure], [Sales Measure])',format:'percentage',decimals:2,enabled:true};
const settings={customKpis:[kpi],alwaysFilter:{field:'Year',values:['2026']}};
const response=await session.answer('Show Rent ratio by Assigned Group',settings);
assert.ok(response.table,JSON.stringify(response));
const rows=response.table.rows;
assert.equal(response.table.modelRawTotals[1],900/(170/3));
assert.equal(response.table.modelRawRows[rows.findIndex(r=>r[0]==='Furniture')][1],12.5);
const chart=await session.answer('Show Rent ratio by Assigned Group as a bar chart',settings);assert.ok(chart.chart);
const matrix=await session.answer('Matrix; rows: Assigned Group; columns: Assigned Tenant Name; values: Rent ratio',settings);assert.ok(matrix.table);
assert(f.queries.filter(q=>q.includes('"M0"')).every(q=>q.includes("'Retail'[Year]")),'Always filter must reach all dependency queries');
assert(f.queries.every(q=>!q.includes('[Rent ratio]')),'Never submit a visual-only KPI as a model measure');
const ranked=await session.answer('Show top 1 Assigned Group by Rent ratio',settings);assert.equal(ranked.table.rows[0][0],'Furniture');
console.log('Teams Custom KPI transport, model totals, charts, matrix, ranking and Always filter passed.');

const transactionSettings={...settings,analysis:{draft:{transactionFields:['Assigned Tenant Name']}}};
const transactionQuestion=';transactions:'+encodeURIComponent(JSON.stringify([{question:'Show Rent ratio by Assigned Group',measure:'Rent ratio',selections:[[{table:'Retail',column:'Assigned Group',value:'Furniture'}]]}]));
const details=await session.answer(transactionQuestion,transactionSettings);
assert.ok(details.transactionTables?.length);
assert.equal(details.table.modelRawTotals[1],12.5);
assert.deepEqual(details.table.rows.map(r=>r[0]).sort(),['Bright Home','Home Living']);
assert(f.queries.every(q=>!q.includes('[Rent ratio]')));
console.log('Ordinary KPI transactions preserve clicked member, Always filter and model ratio total.');

const summaryQuery=';transactions:'+encodeURIComponent(JSON.stringify([{question:'Show Rent ratio by Assigned Group',measure:'Rent ratio',summarizeBy:'City',selections:[[{table:'Retail',column:'Assigned Group',value:'Furniture'}]]}]));
const summary=await session.answer(summaryQuery,settings);
assert.equal(summary.table.columns[0],'City');
assert.equal(summary.table.modelRawTotals[1],12.5);
assert.deepEqual(summary.table.rows.map(r=>r[0]).sort(),['Doha','Riyadh']);
console.log('Summarize by preserves Always filter, selected group and recalculated KPI total without transaction configuration.');

const groupedSettings={...settings,answerGroups:[{id:'fields',name:'Tenant details',kind:'field',members:['Assigned Tenant Name','City'],aliases:['tenant profile'],enabled:true},{id:'measures',name:'Unit performance',kind:'measure',members:['Rent Measure','Rent ratio'],aliases:['performance'],enabled:true}]};
const grouped=await session.answer('Show performance by tenant profile',groupedSettings);
assert.deepEqual(grouped.table.columns,['Assigned Tenant Name','City','Rent Measure','Rent ratio']);
assert.equal(grouped.table.modelRawTotals[2],900);
assert.equal(grouped.table.modelRawTotals[3],900/(170/3));
assert(!grouped.table.columns.includes('Sales Measure'),'KPI dependency stays hidden');
const groupSummary=await session.answer(';transactions:'+encodeURIComponent(JSON.stringify([{question:'Show Rent ratio by Assigned Group',summarizeBy:'Tenant details'}])),groupedSettings);
assert.equal(groupSummary.table.analysisGroupCount,2);
console.log('Teams field/measure groups preserve KPI aggregate totals, hidden dependencies, Always filters and grouped summaries.');

const hiddenGroups=groupedSettings.answerGroups.map(g=>g.kind==='field'?{...g,hiddenMembers:['City']}:{...g,members:['Rent Measure','Sales Measure','Rent ratio'],hiddenMembers:['Sales Measure']});
const hiddenAnswer=await session.answer('Show performance by tenant profile',{...groupedSettings,answerGroups:hiddenGroups});
assert.deepEqual(hiddenAnswer.table.columns,['Assigned Tenant Name','Rent Measure','Rent ratio']);
assert.equal(hiddenAnswer.table.modelRawTotals[2],900/(170/3));

const filterGroups=groupedSettings.answerGroups.map(g=>g.kind==='field'?{...g,hiddenMembers:['City'],filters:[{field:'City',values:['Riyadh']}]}:g);
const groupFilteredSettings={...groupedSettings,answerGroups:filterGroups};
const groupFilteredAnswer=await session.answer('Show performance by tenant profile',groupFilteredSettings);
assert.deepEqual(groupFilteredAnswer.table.columns,['Assigned Tenant Name','Rent Measure','Rent ratio']);
assert.equal(groupFilteredAnswer.table.modelRawTotals[1],300);
assert.equal(groupFilteredAnswer.table.modelRawTotals[2],5);
const filteredSummary=await session.answer(';transactions:'+encodeURIComponent(JSON.stringify([{question:'Show Rent ratio by Assigned Group',summarizeBy:'Tenant details'}])),groupFilteredSettings);
assert.equal(filteredSummary.table.modelRawTotals.at(-1),5);
await assert.rejects(()=>session.answer('Show performance by tenant profile where City = Doha',groupFilteredSettings),/conflicts with Group filter/);
console.log('Group filters reach hidden-field queries, KPI totals, Always filter intersections and summaries.');

const filteredKpi={...kpi,id:'filtered',name:'Riyadh ratio',filters:[{field:'City',values:['Riyadh']}]};
const scopedKpiSettings={...settings,customKpis:[filteredKpi,{...kpi,id:'nested-filter',name:'Double filtered ratio',formula:'[Riyadh ratio] * 2'}]};
const scopedKpiAnswer=await session.answer('Show Rent Measure and Riyadh ratio and Double filtered ratio by Assigned Group',scopedKpiSettings);
assert.equal(scopedKpiAnswer.table.modelRawTotals[1],900,'unrelated measure keeps original scope');
assert.equal(scopedKpiAnswer.table.modelRawTotals[2],5,'filtered ratio uses model totals within City');
assert.equal(scopedKpiAnswer.table.modelRawTotals[3],10,'nested KPI inherits child filter');
const fashionIndex=scopedKpiAnswer.table.rows.findIndex(r=>r[0]==='Fashion');
assert.equal(scopedKpiAnswer.table.modelRawRows[fashionIndex][1],400);
assert.equal(scopedKpiAnswer.table.modelRawRows[fashionIndex][2],null,'unfiltered-only rows remain with blank filtered KPI');
const scopedMatrix=await session.answer('Matrix; rows: Assigned Group; columns: City; values: Rent Measure and Riyadh ratio',scopedKpiSettings);assert.ok(scopedMatrix.table);
await assert.rejects(()=>session.answer('Riyadh ratio by Assigned Group where City = Doha',scopedKpiSettings),/conflicts with KPI filter/);
console.log('KPI filters: independent measure scopes, nested filters, model totals, matrix and conflicts passed.');
const filteredMeasureGroup={id:'filtered-measures',name:'Local performance',kind:'measure',members:['Rent Measure','Sales Measure'],aliases:['local metrics'],enabled:true,filters:[{field:'City',values:['Riyadh']}]};
const localMetrics=await session.answer('Show local metrics by Assigned Group',{...settings,answerGroups:[filteredMeasureGroup]});
assert.equal(localMetrics.table.modelRawTotals[1],300);
assert.equal(localMetrics.table.modelRawTotals[2],60);
await assert.rejects(()=>session.answer('Show local metrics by Assigned Group where City = Doha',{...settings,answerGroups:[filteredMeasureGroup]}),/conflicts/);
console.log('Measure group filters apply to every measure and reject conflicting question filters.');
const groupWaterfall=await session.answer('Show Rent Measure by Tenant details as a waterfall chart',groupedSettings);
assert.equal(groupWaterfall.chart.type,'waterfall');
assert.deepEqual(groupWaterfall.chart.groupNames,['Assigned Tenant Name','City']);
