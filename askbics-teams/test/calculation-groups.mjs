import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {model,fixture} from './visual-fixture.mjs';
const {ModelSession}=createRequire(import.meta.url)('../dist/visual-server.cjs');
const f=fixture(),session=new ModelSession(model,'fixture-token',f.fetcher);
const measure={id:'ratio',name:'Rental ratio',description:'',formula:"('Rent Measure') / ('Sales Measure')",enabled:true,format:'number',decimals:2,total:'recalculate'};
const settings={calculationGroups:[{version:1,id:'finance',name:'Finance',description:'',enabled:true,measures:[measure]}],alwaysFilter:{field:'Year',values:['2026']}};
const response=await session.answer('Show #calc[finance] by Assigned Group',settings);
assert.ok(response.table);
assert.deepEqual(response.table.columns,['Assigned Group','Calculation','Value']);
assert.equal(response.table.modelRawRows[response.table.totalRowIndices[0]][2],900/(170/3));
assert.equal(response.table.modelRawRows[response.table.rows.findIndex(r=>r[0]==='Furniture')][2],12.5);
assert(Object.values(JSON.parse(JSON.stringify(response)).table.calculationNotes).some(notes=>notes.some(n=>n.includes('Rent Measure ='))));
assert(f.queries.every(q=>!q.includes('[Rental ratio]')));
assert(f.queries.some(q=>q.includes('[Rent Measure]')&&q.includes('[Sales Measure]')),'Numerator and denominator share a model query');
assert.equal(f.queries.filter(q=>q.includes('"M0"')).length,2,'Calculation data uses grouped and model-total DAX, without redundant operand/total requests');
assert(f.queries.filter(q=>q.includes('"M0"')).every(q=>q.includes("'Retail'[Year]")));
const matrix=await session.answer('Matrix; rows: Assigned Group; columns: Assigned Tenant Name; values: Rental ratio',settings);
assert(matrix.table);
assert(Object.values(matrix.table.calculationNotes || {}).some(notes=>notes.some(n=>n.includes('Rent Measure ='))), 'Matrix cells retain calculation breakdowns');
const combined=structuredClone(settings);
combined.calculationGroups[0].measures[0].formula="(('Rent Measure') + ('Sales Measure'), [Year] = 2026) / ('Sales Measure')";
const shared=await session.answer('Show #calc[finance] by Assigned Group',combined);
assert.ok(shared.table);assert.equal(shared.table.modelRawRows[shared.table.totalRowIndices[0]][2],(900+170/3)/(170/3));
assert(Object.values(shared.table.calculationNotes).some(notes=>notes.some(n=>n.includes('filtered'))));
console.log('Calculation groups Teams transport, shared expressions, totals, matrix and breakdown passed.');
